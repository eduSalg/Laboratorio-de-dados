-- SE QUISERMOS SABER QUANTAS TURMAS EXISTEM NA TABELA TURMA
-- PODEMOS USAR UMA FUNÇÃO AGREGADA
SELECT COUNT(*) AS 'QUANTIDADE DE TURMAS'
FROM TURMA;

-- PARA EVITAR A CONTAGEM DE LINHAS DUPLICADAS
SELECT COUNT(DESCRICAO) AS ' QUANTIDADE DE TURMAS'
FROM TURMA AS TU
WHERE TU.DESCRICAO LIKE ' TURMA 01';

-- EXCLUINDO TUPLAS (LINHAS)DUPLICADAS
SELECT COUNT( DISTINCT DESCRICAO) AS 'QUANTIDADE DE TURMAS'
FROM TURMA AS TU;

-- VERIFICANDO A MAIOR E MENOR NOTA DA TABELA AVALIAÇÃO
SELECT MIN(AV.NT_AVALIACAO)
FROM AVALIACAO AS AV;

SELECT MAX(AV.NT_AVALIACAO)
FROM AVALIACAO AS AV;

-- VERIFICANDO A MÉDIA ARITMETICA SIMPLES DA TABELA AVALIACAO
SELECT SUM(AV.NT_AVALIACAO)/ COUNT(AV.NT_AVALIACAO) AS 'MÉDIA DE NOTAS'
FROM AVALIACAO AS AV;

-- POSSO TAMBEM USAR O METODO AVG (AVAREGE) DA MÉDIA ARITMETICA SIMPLES DA TABELA 
SELECT AVG(AV.NT_AVALIACAO) AS 'MÉDIA DE NOTAS'
FROM AVALIACAO AS AV;

