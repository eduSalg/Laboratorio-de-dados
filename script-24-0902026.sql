-- CONSULTANDO DADOS DE DUAS TABELAS
-- APRESENTANDO O CÓDIGO DO CURSO E NOME RELACIONADO COM CÓDIGO DA TURMA,
-- SEU ANO E NOME(DESCRICAO)
-- COM JUNÇÃO INPLICITA DE FORMA NATIVA

SELECT CURSO.CO_CURSO AS 'CÓDIGO DO CURSO',
CURSO.NOME AS 'NOME DO CURSO',
TURMA.CO_TURMA AS 'CÓDIGO DA TURMA',
TURMA.DESCRICAO AS 'NOME DA TURMA',
TURMA.ANO AS 'ANO DE INÍCIO DA TURMA'

 FROM CURSO INNER JOIN TURMA ON (CURSO.CO_CURSO = TURMA.CO_CURSO); -- JUNÇÃO IMPLÍCITA

SELECT CURSO.CO_CURSO AS 'CÓDIGO DO CURSO',
CURSO.NOME AS 'NOME DO CURSO',
TURMA.CO_TURMA AS 'CÓDIGO DA TURMA',
TURMA.DESCRICAO AS 'NOME DA TURMA',
TURMA.ANO AS 'ANO DE INÍCIO DA TURMA'
FROM CURSO, TURMA
WHERE CURSO.CO_CURSO = TURMA.CO_CURSO;


